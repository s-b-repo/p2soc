//! `soc.env`: rendering, parsing and in-place rewriting.
//!
//! The file is shell-sourced by the launcher scripts, so values are quoted
//! for a shell on the way out; reading treats them as data (one layer of
//! matching quotes removed, no expansion, nothing executed).

use crate::error::{Result, SetupError};
use crate::util::utc_stamp;
use soc_sys::fsutil;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::time::SystemTime;

/// A parsed or to-be-rendered `soc.env`: `KEY -> value`.
pub type SocEnv = BTreeMap<String, String>;

/// Defaults for keys a `soc.env` predating them does not have, so re-rendering
/// an old file can neither fail nor quietly drop a setting.
pub const SOC_ENV_DEFAULTS: [(&str, &str); 11] = [
    ("SOC_VAULT_BACKEND", "litebw"),
    ("SOC_VAULT_EMAIL", ""),
    ("SOC_VAULT_URL", "http://127.0.0.1:8222"),
    ("SOC_ROOT", "/opt/soc-display"),
    ("SOC_PANELS_FILE", "/etc/soc-display/panels.yaml"),
    ("SOC_INJECT_TMPL", "/opt/soc-display/inject/login.js.tmpl"),
    ("SOC_LAUNCH_STAGGER", "1.5"),
    ("SOC_READY_TIMEOUT", "120"),
    ("SOC_CDP_BASE_PORT", "9222"),
    ("SOC_CRED_TTL", "30"),
    ("SOC_VPN_DRY_RUN", "0"),
];

/// Keys `render_soc_env` writes itself besides [`SOC_ENV_DEFAULTS`].
const RENDERED_EXTRA: [&str; 6] = [
    "SOC_SECRET_DIR",
    "SOC_CONFIG_VAULT_ITEM",
    "SOC_MASTER_SOURCE",
    "SOC_MEM_MIN_AVAIL_MB",
    "SOC_SESSION",
    "SOC_UNATTENDED",
];

/// Keys that are never carried forward on a re-render: a plaintext master and
/// the legacy pinentry pointer.
pub const NEVER_KEPT: [&str; 2] = ["SOC_VAULT_PASSWORD", "SOC_PINENTRY"];

fn default_for(key: &str) -> &'static str {
    SOC_ENV_DEFAULTS.iter().find(|(k, _)| *k == key).map_or("", |(_, v)| v)
}

fn is_rendered(key: &str) -> bool {
    SOC_ENV_DEFAULTS.iter().any(|(k, _)| *k == key) || RENDERED_EXTRA.contains(&key)
}

fn safe_char(c: char) -> bool {
    c.is_ascii_alphanumeric() || matches!(c, '_' | '@' | '%' | '+' | '=' | ':' | ',' | '.' | '/' | '-')
}

/// Quote a value for a shell-sourced env file: bare when it only holds safe
/// characters, otherwise single-quoted with embedded quotes escaped.
///
/// (The Python original used `re.match(..$)`, whose `$` also matches before a
/// trailing newline, so `"x\n"` was written bare. Here a newline always forces
/// quoting.)
pub fn envq(v: &str) -> String {
    if v.is_empty() || v.chars().all(safe_char) {
        return v.to_string();
    }
    format!("'{}'", v.replace('\'', "'\\''"))
}

/// The `soc.env` text. Non-secret by construction: the vault master is sealed
/// host-bound and never appears here, and a plaintext one in `e` is dropped.
pub fn render_soc_env(e: &SocEnv) -> String {
    // `e.get(k) or default`: an empty value also falls back to the default.
    let get = |k: &str| e.get(k).filter(|v| !v.is_empty()).map_or_else(|| default_for(k).to_string(), Clone::clone);
    let mut l: Vec<String> = vec![
        "# SOC kiosk environment — generated by setup.py. NON-SECRET.".into(),
        "# The vault master password is NOT here: it is sealed host-bound under".into(),
        "# $SOC_SECRET_DIR and fed to litebw by pinentry-vault.py (no .env secret).".into(),
        "# The wall config lives in Vaultwarden (SOC_CONFIG_VAULT_ITEM). See".into(),
        "# docs/SECURITY.md.".into(),
        String::new(),
        "# --- vault (litebw -> Vaultwarden) ---".into(),
    ];
    for k in ["SOC_VAULT_BACKEND", "SOC_VAULT_EMAIL", "SOC_VAULT_URL"] {
        l.push(format!("{k}={}", envq(&get(k))));
    }
    let raw = |k: &str, dflt: &str| e.get(k).map_or_else(|| dflt.to_string(), Clone::clone);
    l.push(format!("SOC_SECRET_DIR={}", envq(&raw("SOC_SECRET_DIR", ""))));
    l.push(format!("SOC_CONFIG_VAULT_ITEM={}", envq(&raw("SOC_CONFIG_VAULT_ITEM", "SOC Wall Config"))));
    if let Some(src) = e.get("SOC_MASTER_SOURCE").filter(|v| !v.is_empty()) {
        l.push(format!("SOC_MASTER_SOURCE={}", envq(src)));
    }
    l.push(String::new());
    l.push("# --- paths ---".into());
    for k in ["SOC_ROOT", "SOC_PANELS_FILE", "SOC_INJECT_TMPL"] {
        l.push(format!("{k}={}", envq(&get(k))));
    }
    l.push(String::new());
    l.push("# --- host tuning ---".into());
    for k in ["SOC_LAUNCH_STAGGER", "SOC_READY_TIMEOUT", "SOC_CDP_BASE_PORT", "SOC_CRED_TTL", "SOC_VPN_DRY_RUN"] {
        l.push(format!("{k}={}", envq(&get(k))));
    }
    let mem = e.get("SOC_MEM_MIN_AVAIL_MB").filter(|v| !v.is_empty()).map_or("150", String::as_str);
    l.push(format!("SOC_MEM_MIN_AVAIL_MB={}", envq(mem)));
    l.push(String::new());
    l.push("# --- display stack: auto|wayland|xwayland|xlibre|xorg|x11 ---".into());
    l.push(format!("SOC_SESSION={}", envq(&raw("SOC_SESSION", "auto"))));
    // Written by install.sh on a kiosk; a re-render must not lose it.
    if let Some(v) = e.get("SOC_UNATTENDED").filter(|v| !v.is_empty()) {
        l.push(String::new());
        l.push("# --- kiosk: never wait for a human; retry forever ---".into());
        l.push(format!("SOC_UNATTENDED={}", envq(v)));
    }
    // Everything else the operator set survives a re-render: dropping unknown
    // keys would silently undo settings like SOC_ONSCREEN_CONFIG=0.
    let kept: Vec<(&String, &String)> = e
        .iter()
        .filter(|(k, _)| k.starts_with("SOC_") && !is_rendered(k) && !NEVER_KEPT.contains(&k.as_str()))
        .collect();
    if !kept.is_empty() {
        l.push(String::new());
        l.push("# --- operator settings ---".into());
        l.extend(kept.iter().map(|(k, v)| format!("{k}={}", envq(v))));
    }
    l.push(String::new());
    l.join("\n")
}

/// Parse `KEY=VALUE` text (comments / lines without `=` skipped, one layer of
/// matching quotes removed). Data only: nothing is expanded or executed.
pub fn parse_env_file(text: &str) -> SocEnv {
    soc_sys::health::parse_env(text)
}

/// [`parse_env_file`] of a file; empty when it is missing or unreadable.
pub fn load_env_file(path: &Path) -> SocEnv {
    soc_sys::health::load_env_file(path)
}

/// What [`rewrite_env`] should change.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Changes {
    /// Keys whose lines are dropped.
    pub remove: BTreeSet<String>,
    /// Keys to update in place, or append when absent, in append order.
    pub set: Vec<(String, String)>,
}

impl Changes {
    pub fn new() -> Changes {
        Changes::default()
    }

    pub fn remove(mut self, key: &str) -> Changes {
        self.remove.insert(key.to_string());
        self
    }

    pub fn set(mut self, key: &str, value: &str) -> Changes {
        match self.set.iter_mut().find(|(k, _)| k == key) {
            Some(slot) => slot.1 = value.to_string(),
            None => self.set.push((key.to_string(), value.to_string())),
        }
        self
    }

    pub fn is_empty(&self) -> bool {
        self.remove.is_empty() && self.set.is_empty()
    }
}

/// What a [`rewrite_env`] call did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Rewrite {
    /// The file does not exist; nothing was done (as in the Python tool).
    Missing,
    /// The new text was computed but, in a dry run, not written.
    DryRun(String),
    /// Rewritten; the previous contents are in `backup` when one was made.
    Written { backup: Option<PathBuf> },
}

/// The rewritten text: drop `remove` keys, update `set` keys in place (all
/// occurrences), append the ones not present. Comments, blank lines and order
/// survive. Values are `envq`-quoted, so a path with a space stays sourceable.
pub fn apply_changes(text: &str, changes: &Changes) -> String {
    let mut out = String::with_capacity(text.len());
    let mut seen: BTreeSet<&str> = BTreeSet::new();
    for line in text.split_inclusive('\n') {
        let s = line.trim();
        if !s.is_empty() && !s.starts_with('#') {
            if let Some((k, _)) = s.split_once('=') {
                let k = k.trim();
                if changes.remove.contains(k) {
                    continue;
                }
                if let Some((key, value)) = changes.set.iter().find(|(sk, _)| sk == k) {
                    out.push_str(&format!("{key}={}\n", envq(value)));
                    seen.insert(key.as_str());
                    continue;
                }
            }
        }
        out.push_str(line);
    }
    for (k, v) in &changes.set {
        if !seen.contains(k.as_str()) {
            // A last line without a newline must not swallow the appended key.
            if !out.is_empty() && !out.ends_with('\n') {
                out.push('\n');
            }
            out.push_str(&format!("{k}={}\n", envq(v)));
        }
    }
    out
}

/// Copy `path` to `path.bak.<stamp>`. `Ok(None)` when it does not exist or
/// cannot be read by this user (the original is untouched either way).
pub fn backup(path: &Path) -> Option<PathBuf> {
    if !path.exists() {
        return None;
    }
    let mut name = path.as_os_str().to_os_string();
    name.push(format!(".bak.{}", utc_stamp(SystemTime::now())));
    let bak = PathBuf::from(name);
    fs::copy(path, &bak).ok().map(|_| bak) // audit-allow: a non-root user cannot back up a root-owned file; the original is untouched
}

/// Rewrite a `soc.env` in place, atomically, with `mode` set before the new
/// content is visible. Backs the old file up first. A missing file is a no-op.
pub fn rewrite_env(path: &Path, changes: &Changes, mode: u32, dry: bool) -> Result<Rewrite> {
    if !path.exists() {
        return Ok(Rewrite::Missing);
    }
    let text = fsutil::read_capped(path, 1 << 20).map_err(|e| SetupError::io("cannot read", path, e))?;
    let new = apply_changes(&text, changes);
    if dry {
        return Ok(Rewrite::DryRun(new));
    }
    let bak = backup(path);
    fsutil::write_atomic(path, new.as_bytes(), mode).map_err(|e| SetupError::io("cannot write", path, e))?;
    Ok(Rewrite::Written { backup: bak })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn envq_cases() {
        assert_eq!(envq(""), "");
        assert_eq!(envq("a/b:c@d%e+f=g,h.i-j_k"), "a/b:c@d%e+f=g,h.i-j_k");
        assert_eq!(envq("a b"), "'a b'");
        assert_eq!(envq("it's"), "'it'\\''s'");
        assert_eq!(envq("x\n"), "'x\n'");
        assert_eq!(envq("café"), "'café'");
    }

    #[test]
    fn append_after_unterminated_last_line() {
        let out = apply_changes("A=1", &Changes::new().set("B", "2"));
        assert_eq!(out, "A=1\nB=2\n");
    }

    #[test]
    fn set_values_are_quoted_for_the_shell() {
        let out = apply_changes("P=old\n", &Changes::new().set("P", "/opt/a b/x"));
        assert_eq!(out, "P='/opt/a b/x'\n");
    }
}
