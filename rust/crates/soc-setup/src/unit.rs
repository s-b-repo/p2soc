//! The supervised `soc-wall.service` unit: rendering, and reading the baked
//! `Environment=` lines back.

use crate::envfile::SocEnv;
use soc_sys::fsutil;
use std::collections::BTreeMap;
use std::path::Path;

/// The non-secret keys baked into the unit's `Environment=` lines. The vault
/// master is never among them: it is sealed host-bound.
pub const WALL_ENV_KEYS: [&str; 17] = [
    "SOC_VAULT_BACKEND",
    "SOC_VAULT_EMAIL",
    "SOC_VAULT_URL",
    "SOC_SECRET_DIR",
    "SOC_MASTER_SOURCE",
    "SOC_SECRET_ATTRS",
    "SOC_CONFIG_VAULT_ITEM",
    "SOC_ROOT",
    "SOC_PANELS_FILE",
    "SOC_INJECT_TMPL",
    "SOC_LAUNCH_STAGGER",
    "SOC_READY_TIMEOUT",
    "SOC_CDP_BASE_PORT",
    "SOC_CRED_TTL",
    "SOC_VPN_DRY_RUN",
    "SOC_SESSION",
    "SOC_UNATTENDED",
];

/// Non-environment inputs of the unit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnitOpts {
    /// `User=` of the session.
    pub user: String,
    /// Where the release lives (`ExecStart=<root>/scripts/start-session.sh`).
    pub soc_root: String,
}

impl Default for UnitOpts {
    fn default() -> UnitOpts {
        UnitOpts { user: "soc".into(), soc_root: "/opt/soc-display".into() }
    }
}

/// The unit text: the kiosk session as a systemd service with the non-secret
/// config baked in as `Environment=` lines (no `soc.env`) and `Restart=always`.
pub fn render_wall_unit(e: &SocEnv, opts: &UnitOpts) -> String {
    // systemd needs the whole assignment quoted when the value has spaces.
    let env_line = |k: &str, v: &str| {
        if v.contains(' ') { format!("Environment=\"{k}={v}\"") } else { format!("Environment={k}={v}") }
    };
    let mut l: Vec<String> = [
        "# SOC video-wall kiosk session — generated by setup.py.",
        "# Non-secret config is baked in as Environment= below (no soc.env).",
        "# The vault master is sealed host-bound under $SOC_SECRET_DIR.",
        "[Unit]",
        "Description=SOC video-wall kiosk session",
        "After=systemd-user-sessions.service network-online.target vaultwarden.service",
        "Wants=network-online.target vaultwarden.service",
        "Conflicts=getty@tty1.service",
        "After=getty@tty1.service",
        "",
        "[Service]",
        "Type=simple",
    ]
    .iter()
    .map(|s| (*s).to_string())
    .collect();
    l.push(format!("User={}", opts.user));
    l.extend(
        [
            "PAMName=login",
            "TTYPath=/dev/tty1",
            "StandardInput=tty",
            "StandardOutput=journal",
            "StandardError=journal",
            "TTYReset=yes",
            "TTYVHangup=yes",
            "UtmpIdentifier=tty1",
            "UtmpMode=user",
            "",
        ]
        .iter()
        .map(|s| (*s).to_string()),
    );
    l.extend(WALL_ENV_KEYS.iter().map(|k| env_line(k, e.get(*k).map_or("", String::as_str))));
    l.extend(
        [
            "# Recycle a panel before the cgroup starts thrash-reclaiming.",
            "Environment=SOC_MEM_MIN_AVAIL_MB=150",
            "# Physical-access config surface: off by default, PIN mandatory if enabled.",
            "Environment=SOC_ONSCREEN_CONFIG=0",
            "Environment=SOC_CONFIG_REQUIRE_PIN=1",
            "",
        ]
        .iter()
        .map(|s| (*s).to_string()),
    );
    l.push(format!("ExecStart={}/scripts/start-session.sh", opts.soc_root));
    l.extend(
        [
            "Restart=always",
            "RestartSec=3",
            "# MemoryHigh throttles a leaking dashboard through kernel reclaim. No hard",
            "# MemoryMax on purpose: that OOM-kills inside the cgroup and blanks the WHOLE",
            "# wall before the host's memory watchdog can recycle a single panel.",
            "MemoryAccounting=yes",
            "MemoryHigh=80%",
            "LimitCORE=0",
            "LimitNPROC=256",
            "LimitNOFILE=8192",
            "TasksMax=512",
            "ProtectClock=yes",
            "ProtectHostname=yes",
            "ProtectKernelLogs=yes",
            "LockPersonality=yes",
            "RestrictRealtime=yes",
            "",
            "[Install]",
            "WantedBy=graphical.target",
            "",
        ]
        .iter()
        .map(|s| (*s).to_string()),
    );
    l.join("\n")
}

/// Read the config back out of a unit's `Environment=` lines. Data only. Each
/// line is one `KEY=VALUE` (a whole-assignment `"..."` quote is removed); a
/// hand-written `Environment=A=1 B=2` therefore yields `A -> "1 B=2"`, exactly
/// as the Python reader did.
pub fn parse_unit_env(text: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for line in text.lines() {
        let Some(body) = line.trim().strip_prefix("Environment=") else { continue };
        let mut body = body.trim();
        if body.len() >= 2 {
            if let Some(inner) = body.strip_prefix('"').and_then(|b| b.strip_suffix('"')) {
                body = inner;
            }
        }
        if let Some((k, v)) = body.split_once('=') {
            out.insert(k.trim().to_string(), v.to_string());
        }
    }
    out
}

/// [`parse_unit_env`] of a file; empty when it is missing or unreadable.
pub fn load_unit_env(path: &Path) -> BTreeMap<String, String> {
    fsutil::read_capped(path, 1 << 20).map(|t| parse_unit_env(&t)).unwrap_or_default() // audit-allow: empty is the intended fallback for an unreadable unit
}
