//! Protocol constants for the H3C iNode SSL VPN ("V7") wire protocol.
//!
//! A faithful port of `backends/h3csvpn/constants.py`. Every value was
//! recovered from the unstripped Linux iNode 7.3 client (`libiNodeSslvpnPt.so`
//! / `libvnic.so`); nothing here is invented.

// ---- transport ------------------------------------------------------------
pub const DEFAULT_PORT: u16 = 443;
pub const HTTP_VERSION: &str = "HTTP/1.1";
pub const UA_V7: &str = "SSLVPN-Client/7.0";
pub const UA_V3: &str = "SSLVPN-Client/3.0";

/// Response header that marks a V7 gateway (else assume V3).
pub const VERSION_SENTINEL: &str = "SSLVPN-Gateway/7.0";

pub const FORM_CONTENT_TYPE: &str = "application/x-www-form-urlencoded";
/// POST body is `request=<urlencoded xml>`.
pub const V7_FORM_KEY: &str = "request=";
/// Every body/response is `<data>...</data>`.
pub const XML_ROOT: &str = "data";

// ---- cookies --------------------------------------------------------------
/// Server-issued opaque session token.
pub const SESSION_COOKIE: &str = "svpnginfo";
pub const CAPTCHA_COOKIES: [&str; 3] = ["svpnvldid", "svpnuid", "vldID"];
/// Cookie sent with the domain-list request (`{}` is the domain id).
pub const DOMAIN_COOKIE_PREFIX: &str = "domainId=";
pub const DOMAIN_COOKIE_SUFFIX: &str = "; authId=-1; showOption=1; saveFlag=0; UserName=";

// ---- CGI paths (defaults; the real ones are discovered from gatewayinfo) --
pub const PATH_INDEX: &str = "/svpn/index.cgi";
pub const PATH_IMAGE: &str = "/svpn/image.cgi";
pub const PATH_LOGIN_V7: &str = "/svpn/vpnuser/check.cgi";
pub const PATH_CHALLENGE_V7: &str = "/svpn/vpnuser/check_return.cgi";
pub const PATH_LOGIN_V3: &str = "/svpn/vpnuser/login_submit.cgi";
pub const PATH_LOGOUT: &str = "/svpn/logout.cgi";

pub const OS_FIELD: &str = "Linux";

// ---- tunnel ---------------------------------------------------------------
/// NET_EXTEND / HTTP/1.1 — the custom upgrade verb.
pub const TUNNEL_VERB: &str = "NET_EXTEND";
/// `[type u8][subtype u8][len u16 BE]`.
pub const FRAME_HEADER_LEN: usize = 4;
/// 81920 — client receive buffer.
pub const BIG_BUF_SIZE: usize = 0x14000;
/// Reassembly cap (>> one max frame of 64 KB).
pub const MAX_FRAME_BUFFER: usize = 1024 * 1024;
pub const ENTUNNEL_Q_MAX: usize = 255;
/// Heartbeat loop tick (the binary usleeps 1_000_000).
pub const HEARTBEAT_TICK: f64 = 1.0;
/// Send a heartbeat every KEEPALIVETIME seconds when the gateway omits it.
pub const DEFAULT_KEEPALIVE_INTERVAL: u64 = 30;
pub const HEARTBEAT_FRAME: [u8; 4] = [0x02, 0x01, 0x00, 0x00];
/// Offline after N unanswered heartbeats.
pub const DEFAULT_KEEPALIVE_MAX_MISS: u32 = 5;

// Hard limits to bound memory when talking to a hostile/buggy gateway.
pub const MAX_HEADER_BYTES: usize = 64 * 1024;
pub const MAX_BODY_BYTES: usize = 16 * 1024 * 1024;
pub const MAX_CHUNKS: usize = 100_000;
pub const MAX_EARLY_BYTES: usize = 4 * 1024 * 1024;
pub const MAX_TRAILER_LINES: usize = 100;

// Frame types (uint8 `type` / `subtype`).
/// sub 0 : raw IP packet payload -> TUN.
pub const FRAME_DATA: u8 = 1;
/// sub 1 : keepalive / ack.
pub const FRAME_HEARTBEAT: u8 = 2;
/// sub 1 empty(err) / sub 2 update / sub 3 DTLS(ignore).
pub const FRAME_NETCONFIG: u8 = 3;
/// gateway forced log-off.
pub const FRAME_LOGOFF: u8 = 4;

pub const NETCONFIG_SUB_EMPTY: u8 = 1;
pub const NETCONFIG_SUB_UPDATE: u8 = 2;
pub const NETCONFIG_SUB_DTLS: u8 = 3;

// ---- virtual NIC ----------------------------------------------------------
pub const TUN_DEVICE: &str = "/dev/net/tun";
pub const IFF_TUN: u16 = 0x0001;
pub const IFF_NO_PI: u16 = 0x1000;
/// `TUNSETIFF` ioctl request (Linux, 64-bit).
pub const TUNSETIFF: libc::c_ulong = 0x4004_54CA;
pub const IFNAME_TEMPLATE: &str = "inode%d";
pub const RESOLV_CONF: &str = "/etc/resolv.conf";
pub const RESOLV_MARKER: &str = "#Line Generated by iNode SSL VPN Client";

// ---- Zero-Trust / SPA -----------------------------------------------------
pub const SPA_KNOCK_PORT_GW: u16 = 8000;
pub const SPA_REGISTER_PORT: u16 = 19006;
pub const SPA_KNOCK_PORT: u16 = 59993;
pub const SPA_AUTH_PORT: u16 = 443;
/// u16 at packet offset 0, written native little-endian (`0x0110` -> `10 01`).
pub const SPA_DECLARED_LEN: u16 = 0x0110;
pub const SPA_HEADER_LEN: usize = 0x2F;
pub const SPA_AID_LEN: usize = 32;
/// 5 HOTP digits + 1 Luhn checksum = 6-byte field.
pub const SPA_HOTP_DIGITS: usize = 5;

// ---- wire enums (DWARF const values) --------------------------------------
pub const RESULT_SUCCESS: &str = "Success";
pub const RESULT_CHALLENGE: &str = "Challenge";
